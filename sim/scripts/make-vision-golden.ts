// Writes the golden vision data for the firmware's native tests (docs/system-design.md 9.2, docs/build-plan.md Step 7):
//   shared/golden/vision_frames.bin      a few synthetic template photos, VGA RGB565, losslessly compressed (~80 KB)
//   shared/golden/vision_vectors.json    what vision.ts makes of each case (marks, homography, status, CRCs of every layer, pins, live check)
//   shared/generated/vision_golden.h     the same vectors as C++ initialisers (firmware/test/test_vision reads this and the .bin)
// Run:  npm run golden   (also writes the physics vectors)
import { writeFileSync, mkdirSync } from 'node:fs';
import { renderFrames, packFrames, unpackFrames, runCase, CASES, FRAME_NAMES, CaseResult, Xform, LiveResult } from './vision-golden-lib';

const root = new URL('../../shared/', import.meta.url).pathname;
mkdirSync(root + 'golden', { recursive: true }); mkdirSync(root + 'generated', { recursive: true });

const bin = packFrames(renderFrames());
writeFileSync(root + 'golden/vision_frames.bin', bin);
const frames = unpackFrames(bin);                     // run on what the firmware will load, so the codec is part of the test

const results: CaseResult[] = CASES.map((c) => runCase(frames, c));
writeFileSync(root + 'golden/vision_vectors.json', JSON.stringify({
  _comment: 'vision.ts on each case; the firmware (vision.cpp) must reproduce the marks to 0.1 px and every layer byte for byte. Frames: vision_frames.bin.',
  frames: FRAME_NAMES, cases: results,
}, null, 1));
for (const r of results) console.log(r.name.padEnd(12), 'marks', String(r.marksFound).padEnd(5), 'status', r.status, 'ink', r.inkCover.toFixed(4), 'blobs', String(r.blobs).padStart(3), 'thr', r.usedInkThresh, 'start', r.start.join(','), 'flag', r.flag.join(','));
console.log('wrote vision_frames.bin (' + bin.length + ' bytes) and vision_vectors.json');

// ---- the C++ header ------------------------------------------------------------------------------------------------------
const d = (v: number) => (Object.is(v, -0) ? '0' : String(v));
const arr = (a: number[] | null, n: number) => '{' + (a ?? new Array(n).fill(0)).map(d).join(', ') + '}';
const hq = (a: number[] | null) => '{' + (a ?? new Array(8).fill(0)).map((v) => v + 'LL').join(', ') + '}';
const xf = (x: Xform) => (x.kind === 'none' ? '0, 0, 0' : x.kind === 'dim' ? `1, ${x.k}, 0` : x.kind === 'noise' ? `2, ${x.amp}, ${x.seed}` : x.kind === 'fade' ? `4, ${x.k}, 0` : '3, 0, 0');
const live = (l: LiveResult) => `{${l.upright}, ${l.marks}, ${arr(l.quad, 8)}, ${d(l.distCm)}, ${d(l.edgePx)}, ${d(l.paperMean)}, ${d(l.clipFrac)}, ${d(l.contrast)}, ${d(l.ratioH)}, ${d(l.ratioV)}, ${arr(l.lights, 4)}, ${l.cue}, ${l.allGreen}}`;
const h: string[] = [
  '// GENERATED by sim/scripts/make-vision-golden.ts. DO NOT EDIT. Same data as shared/golden/vision_vectors.json.',
  '#pragma once', '#include <cstdint>', 'namespace vgolden {',
  'struct Params { int inkThresh, closeR, thickenR, minBlob; };                       // -1 = default',
  'struct Rethresh { Params params; int status; double inkCover; int blobs; uint32_t ground, spike, bouncy, scrb; };',
  'struct Live { bool upright, marks; double quad[8]; double distCm, edgePx, paperMean, clipFrac, contrast, ratioH, ratioV; int lights[4]; int cue; bool allGreen; };',
  'struct Case {',
  '  const char* name; int frame; int xform, xa, xb;                                   // xform 0 none, 1 dim (k = xa), 2 noise (amp = xa, seed = xb), 3 rot180, 4 fade (k = xa)',
  '  bool marksFound, orientGuess; double marks[8]; int64_t hq[8];',
  '  int status; double inkCover, bgMean; int blobs; int usedInkThresh; int startX, startY, flagX, flagY;',
  '  uint32_t crcStraight, crcInk, crcCls, crcGround, crcSpike, crcBouncy, crcScrb;',
  '  int nRethresh; Rethresh rethresh[4]; int nLive; Live live[2];',
  '};',
  `static const int nFrames = ${FRAME_NAMES.length};`, 'static const Case cases[] = {',
];
for (const r of results) {
  const p = (x: Partial<Record<string, number>>) => `{${x.inkThresh ?? -1}, ${x.closeR ?? -1}, ${x.thickenR ?? -1}, ${x.minBlob ?? -1}}`;
  const rt = r.rethresh.map((q) => `{${p(q.params as Record<string, number>)}, ${q.status}, ${d(q.inkCover)}, ${q.blobs}, ${q.ground}u, ${q.spike}u, ${q.bouncy}u, ${q.scrb}u}`);
  h.push(`  {"${r.name}", ${r.frame}, ${xf(r.xform)}, ${r.marksFound}, ${r.orientGuess}, ${arr(r.marks, 8)}, ${hq(r.hq)},`,
    `   ${r.status}, ${d(r.inkCover)}, ${d(r.bgMean)}, ${r.blobs}, ${r.usedInkThresh}, ${r.start[0]}, ${r.start[1]}, ${r.flag[0]}, ${r.flag[1]},`,
    `   ${r.crc.straight}u, ${r.crc.ink}u, ${r.crc.cls}u, ${r.crc.ground}u, ${r.crc.spike}u, ${r.crc.bouncy}u, ${r.crc.scrb}u,`,
    `   ${rt.length}, {${rt.join(', ')}}, ${r.live.length}, {${r.live.map(live).join(', ')}}},`);
}
h.push('};', `static const int nCases = ${results.length};`, '}  // namespace vgolden', '');
writeFileSync(root + 'generated/vision_golden.h', h.join('\n'));
console.log('wrote shared/generated/vision_golden.h');
