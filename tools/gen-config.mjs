#!/usr/bin/env node
// Scribble Run - constants generator (MIT).
// Reads shared/constants.json and writes:
//   sim/src/config.ts            (TypeScript, used by the browser simulator)
//   shared/generated/config.h    (C++ header, used later by the firmware and native tests)
// Usage: node tools/gen-config.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(resolve(root, 'shared/constants.json'), 'utf8'));
const c = spec.constants;

// RGB565 = (R & 0xF8) << 8 | (G & 0xFC) << 3 | B >> 3
const rgb565 = (hex) => {
  const r = parseInt(hex.slice(1, 3), 16), g = parseInt(hex.slice(3, 5), 16), b = parseInt(hex.slice(5, 7), 16);
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
};

// Derived values (kept here so TS and C++ always agree).
// The 320x192 level is the mark rectangle shrunk to AREA_SCALE about its centre (docs/system-design.md 5.1),
// so the four mark centres sit OUTSIDE the level, at these level-pixel coordinates:
const cx = c.WORLD_W / 2, cy = c.WORLD_H / 2;
const markDx = cx / c.AREA_SCALE, markDy = cy / c.AREA_SCALE;
const derived = {
  MARK_WORLD_X0: +(cx - markDx).toFixed(4), MARK_WORLD_X1: +(cx + markDx).toFixed(4),
  MARK_WORLD_Y0: +(cy - markDy).toFixed(4), MARK_WORLD_Y1: +(cy + markDy).toFixed(4),
  // millimetres per level pixel
  MM_PER_PX: +((c.TPL_MARK_RECT_W_MM * c.AREA_SCALE) / c.WORLD_W).toFixed(5),
};

const all = { ...c, ...derived };
const ts = [];
ts.push('// GENERATED by tools/gen-config.mjs from shared/constants.json. DO NOT EDIT BY HAND.');
ts.push('// Same names and values as shared/generated/config.h (C++).');
ts.push('');
for (const [k, v] of Object.entries(all)) ts.push(`export const ${k} = ${v};`);
ts.push('');
ts.push('/** Palette as CSS hex strings. */');
ts.push('export const PALETTE_HEX = {');
for (const [k, v] of Object.entries(spec.palette)) ts.push(`  ${k}: '${v}',`);
ts.push('} as const;');
ts.push('');
ts.push('/** Palette as RGB565 (what the M5GFX display uses). */');
ts.push('export const PALETTE_565 = {');
for (const [k, v] of Object.entries(spec.palette)) ts.push(`  ${k}: 0x${rgb565(v).toString(16).toUpperCase().padStart(4, '0')},`);
ts.push('} as const;');
ts.push('');
ts.push('/** Palette order used by 4-bit thumbnails (index 0..8). */');
ts.push('export const PALETTE_ORDER = [' + Object.keys(spec.palette).map((k) => `'${k}'`).join(', ') + '] as const;');
ts.push('');
writeFileSync(resolve(root, 'sim/src/config.ts'), ts.join('\n'));

const h = [];
h.push('// GENERATED by tools/gen-config.mjs from shared/constants.json. DO NOT EDIT BY HAND.');
h.push('// Same names and values as sim/src/config.ts (TypeScript).');
h.push('#pragma once');
h.push('#include <cstdint>');
h.push('namespace scribble {');
for (const [k, v] of Object.entries(all)) {
  const isInt = Number.isInteger(v);
  // fractional constants are double: 0.9f is not the same number as JavaScript's 0.9, and the golden tests compare bit for bit
  h.push(isInt ? `constexpr int32_t ${k} = ${v};` : `constexpr double ${k} = ${v};`);
}
for (const [k, v] of Object.entries(spec.palette)) {
  h.push(`constexpr uint16_t PAL_${k} = 0x${rgb565(v).toString(16).toUpperCase().padStart(4, '0')};`);
}
h.push('}  // namespace scribble');
h.push('');
mkdirSync(resolve(root, 'shared/generated'), { recursive: true });
writeFileSync(resolve(root, 'shared/generated/config.h'), h.join('\n'));
console.log(`wrote sim/src/config.ts and shared/generated/config.h (${Object.keys(all).length} constants)`);
